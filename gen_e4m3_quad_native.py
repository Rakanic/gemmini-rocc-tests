#!/usr/bin/env python3
"""Golden for the native 8-bit E4M3 quad (mode9) build, MxDim32E4M3QuadGemminiRocketConfig (branch large-mesh-fp8).

C (BF16) = A x B with MX E4M3 operands (random full-range codes, random E8M0 block scales). The mesh math is the
E4M3-LUT quad golden's (gen_mx_lut.py): fp8_matmul_model.tiled_matmul_hwlike with TILE = DIM and the DIM-aware
precision ramp; only the operand encoding differs (direct codes, no codebooks). Operand layout, 16-bit lanes with
element 0 in the low byte (what QuantLut's deproject feeds the mesh):
  A_hw[M/2][K]: lane (r, k) = A[2r][k] | A[2r+1][k] << 8
  B_hw[K][N/2]: lane (k, c) = B[k][2c] | B[k][2c+1] << 8
Scales: A_sc[K/32][M], B_sc[K/32][N] (E8M0 codes). Golden: C_out_bf16[M][N]; requant output (gen_matmul_llama's fp8
encoder, the E4M3-single requant golden) as the next matmul's operand A: C_q_hw[M/2][N] lanes + C_scales_out[M][N/32].
--chain adds MM2 = C1 x B2 with C1 = that requant output read back as operand A (its code values + its block scales):
B2_hw[N][N/2], B2_sc[N/32][N], C2_q_hw[M/2][N], C2_scales_out[M][N/32].
"""
import argparse
import os
import sys

here = os.path.dirname(os.path.abspath(__file__))
os.chdir(here)
sys.path.insert(0, here)

import torch
import fp8_matmul_model as fm
from lut_golden_model import tensor_to_custom_fp_codes
from gen_mx_lut import precision_for_dim
from gen_matmul_llama import quantize, FORMATS


def lanes(lo, hi):
    return [[(l & 0xFF) | ((h & 0xFF) << 8) for l, h in zip(rl, rh)] for rl, rh in zip(lo, hi)]


def c_array(ctype, name, rows, fmt):
    body = ",\n".join("  { " + ", ".join(fmt.format(v) for v in r) + " }" for r in rows)
    return f"static const {ctype} {name}[{len(rows)}][{len(rows[0])}] __attribute__((aligned(64))) = {{\n{body}\n}};\n\n"


def main():
    ap = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    ap.add_argument("--dim", type=int, default=32)
    ap.add_argument("--M", type=int, default=64)
    ap.add_argument("--K", type=int, default=64)
    ap.add_argument("--N", type=int, default=64)
    ap.add_argument("--seed", type=int, default=0)
    ap.add_argument("--header-path", type=str, default=None)
    ap.add_argument("--chain", action="store_true")
    a = ap.parse_args()
    M, K, N, dim = a.M, a.K, a.N, a.dim
    assert M % (2 * dim) == 0 and N % (2 * dim) == 0 and K % dim == 0 and K % 32 == 0
    shape = f"{M}x{N}" if M == N == K else f"{M}x{N}x{K}"
    path = a.header_path or f"include/matmul_data_e4m3_quad_{'chain_' if a.chain else ''}{shape}_dim{dim}.h"

    g = torch.Generator().manual_seed(a.seed)
    q = fm.make_fp_quantizer("fp8:e4m3", rounding="zero")
    A = q(torch.randn(M, K, generator=g) * 1.5)
    B = q(torch.randn(K, N, generator=g) * 1.5)
    GK = K // fm.GROUP
    A_sc = torch.pow(2.0, torch.randint(-4, 4, (M, GK), generator=g).float())
    B_sc = torch.pow(2.0, torch.randint(-4, 4, (GK, N), generator=g).float())

    fm.TILE = dim
    prod, acc = precision_for_dim(dim)
    C = fm.tiled_matmul_hwlike(A, B, A_sc, B_sc, verbose=False, prod_precision_list=prod, acc_precision_list=acc)
    assert torch.isfinite(C).all(), "non-finite golden"

    A_codes, _ = tensor_to_custom_fp_codes(A, "fp8:e4m3")
    B_codes, _ = tensor_to_custom_fp_codes(B, "fp8:e4m3")
    A_hw = lanes(A_codes[0::2], A_codes[1::2])
    B_hw = [[(r[2 * c] & 0xFF) | ((r[2 * c + 1] & 0xFF) << 8) for c in range(N // 2)] for r in B_codes]
    As, _ = tensor_to_custom_fp_codes(A_sc.transpose(0, 1).contiguous(), fm.SCALE_SPEC)
    Bs, _ = tensor_to_custom_fp_codes(B_sc, fm.SCALE_SPEC)
    Cb, _ = tensor_to_custom_fp_codes(C, "bf16")
    Cq, Cs, CP = quantize(C.numpy().astype("float32"), axis="row", f=FORMATS["fp8"], pmax_shift=0)
    Cq = Cq.astype(int).tolist()
    Cq_hw = lanes(Cq[0::2], Cq[1::2])
    if a.chain:
        B2 = q(torch.randn(N, N, generator=g) * 1.5)
        B2_sc = torch.pow(2.0, torch.randint(-4, 4, (N // fm.GROUP, N), generator=g).float())
        A2_sc = torch.pow(2.0, torch.from_numpy(Cs.astype("float32")) - 127.0)
        C2 = fm.tiled_matmul_hwlike(torch.from_numpy(CP.astype("float32")), B2, A2_sc, B2_sc, verbose=False,
                                    prod_precision_list=prod, acc_precision_list=acc)
        assert torch.isfinite(C2).all(), "non-finite chain golden"
        C2q, C2s, _ = quantize(C2.numpy().astype("float32"), axis="row", f=FORMATS["fp8"], pmax_shift=0)
        C2q = C2q.astype(int).tolist()
        B2_codes, _ = tensor_to_custom_fp_codes(B2, "fp8:e4m3")
        B2_hw = [[(r[2 * c] & 0xFF) | ((r[2 * c + 1] & 0xFF) << 8) for c in range(N // 2)] for r in B2_codes]
        B2s, _ = tensor_to_custom_fp_codes(B2_sc, fm.SCALE_SPEC)

    guard = path.upper().replace(".", "_").replace("/", "_").replace("-", "_")
    with open(path, "w") as f:
        f.write(f"// Generated by gen_e4m3_quad_native.py --dim {dim} --M {M} --K {K} --N {N} --seed {a.seed}\n")
        f.write(f"#ifndef {guard}\n#define {guard}\n#include <stdint.h>\n\n")
        f.write(f"#define MATMUL_M {M}\n#define MATMUL_K {K}\n#define MATMUL_N {N}\n\n")
        f.write(c_array("uint16_t", "A_hw", A_hw, "0x{:04x}"))
        f.write(c_array("uint16_t", "B_hw", B_hw, "0x{:04x}"))
        f.write(c_array("uint8_t", "A_sc", As, "0x{:02x}"))
        f.write(c_array("uint8_t", "B_sc", Bs, "0x{:02x}"))
        f.write(c_array("uint16_t", "C_out_bf16", Cb, "0x{:04x}"))
        f.write(c_array("uint16_t", "C_q_hw", Cq_hw, "0x{:04x}"))
        f.write(c_array("uint8_t", "C_scales_out", Cs.astype(int).tolist(), "0x{:02x}"))
        if a.chain:
            f.write(c_array("uint16_t", "B2_hw", B2_hw, "0x{:04x}"))
            f.write(c_array("uint8_t", "B2_sc", B2s, "0x{:02x}"))
            f.write(c_array("uint16_t", "C2_q_hw", lanes(C2q[0::2], C2q[1::2]), "0x{:04x}"))
            f.write(c_array("uint8_t", "C2_scales_out", C2s.astype(int).tolist(), "0x{:02x}"))
        f.write(f"#endif // {guard}\n")
    print(f"[gen_e4m3_quad_native] dim={dim} M={M} K={K} N={N} -> {path}")


if __name__ == "__main__":
    main()
